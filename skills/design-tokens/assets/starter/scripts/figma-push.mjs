// Writes the Plugin API scripts that set up a brand's Figma file: collections, variables, text
// styles and effect styles from figma.json, the logo and motif files as components on an Assets
// page, and a pass that binds the standards sheet to all of them. Each script is small enough to run
// in one call, safe to run twice (it updates what exists, by name), and returns what it did.
